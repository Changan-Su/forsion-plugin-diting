// Focused real Electron interactions, called by MODEL_UI=1 node verify/smoke.cjs.
const fs = require('fs'); const path = require('path')
exports.run = async ({ win, T, until, shot, ok, enter, inline, cloudAsr, failNextAsr, vault, home, mainWin }) => {
  const wait = async fn => win.waitForFunction(fn, null, { timeout: 25000 })
  const choose = async (kind, name) => {
    await win.locator('.dt-model-field').nth(kind === 'asr' ? 0 : 1).locator('.model-pill-btn').click()
    await win.locator('.cm-model-row').click()
    await win.locator('.cm-sub[data-pane="model"] .menu-item').filter({ hasText: name }).first().click()
  }
  const scope = async value => {
    await win.locator(`.dt-config-panel input[value="${value}"]`).check()
    await win.locator('.dt-config-panel .primary').click()
    await win.waitForSelector('.dt-config-panel', { state: 'detached' })
  }
  const snap = () => T(() => JSON.parse(JSON.stringify(window.__DITING_TEST__.S.open)))
  await T(() => { localStorage.setItem('plugin.diting.autoSummary', 'false') })
  await win.locator('[data-field="title"]').fill('Space model acceptance')
  await choose('asr', 'Speech probe'); await choose('translation', 'Model A')
  ok('New-record model selection keeps title draft', await win.locator('[data-field="title"]').inputValue() === 'Space model acceptance')
  await win.locator('.dt-config-link').filter({ hasText: '术语表' }).click()
  await win.locator('[data-term-field="from"]').fill('拉比频率'); await win.locator('[data-term-field="to"]').fill('Rabi frequency')
  await win.locator('.dt-config-panel .primary').click()
  await wait(() => window.__DITING_TEST__.prefs().terms['拉比频率'] === 'Rabi frequency')
  ok('Glossary adds a term through Space dialog', await win.locator('.dt-config-term').count() === 1)
  await shot('11-glossary'); await win.keyboard.press('Escape')
  await win.locator('.dt-go').click(); await until('cloud recording live', s => s.phase === 'live')
  await until('cloud transcription and translation', s => s.segs >= 2 && s.tr >= 2)
  await win.locator('[data-act="pause"]').click(); await until('paused', s => s.phase === 'paused')
  await wait(() => !window.__DITING_TEST__.S.open.segments.some(s => s.trState === 'wait'))
  await win.waitForTimeout(1500)
  let rec = await snap()
  ok('Space ASR overrides global offline routing over real IPC', cloudAsr.length >= 2 && cloudAsr.every(b => b.includes('speech')) && rec.segments.every(s => s.asrModel?.id === 'probe/speech'))
  ok('Glossary applies to later recognition', rec.segments.every(s => s.text.includes('Rabi frequency')))
  ok('Selected translation id reaches engine request', inline.filter(b => b.selection).every(b => b.model_id === 'm1'))
  failNextAsr()
  await win.locator('[data-act="resume"]').click()
  await wait(() => window.__DITING_TEST__.S.open.segments.some(s => s.fail))
  await win.locator('[data-act="pause"]').click(); await until('paused after failure', s => s.phase === 'paused')
  await win.locator('[data-act="retryAll"]').click()
  await wait(() => !window.__DITING_TEST__.S.open.segments.some(s => s.fail || s.trState === 'wait'))
  ok('Batch retry recovers an actual failed ASR request', (await snap()).segments.every(s => !s.fail && s.asrModel?.id === 'probe/speech'))
  const cloudCount = (await snap()).segments.length
  await choose('asr', 'SenseVoice')
  await wait(() => window.__DITING_TEST__.S.open.asrModel === 'local')
  await win.locator('[data-act="resume"]').click()
  await wait(() => window.__DITING_TEST__.S.open.segments.some(s => s.asrModel?.id === 'local'))
  await win.locator('[data-act="pause"]').click(); await until('paused offline', s => s.phase === 'paused')
  await wait(() => !window.__DITING_TEST__.S.open.segments.some(s => s.trState === 'wait'))
  rec = await snap()
  ok('Switch to on-device ASR affects later audio only', rec.segments.slice(0, cloudCount).every(s => s.asrModel.id === 'probe/speech') && rec.segments.some(s => s.asrModel?.id === 'local' && s.text))
  await choose('asr', 'Speech probe'); await wait(() => window.__DITING_TEST__.S.open.asrModel === 'probe/speech')
  rec = await snap()
  const before = JSON.stringify(rec.segments); let start = inline.length
  await choose('translation', 'Model B'); await shot('12-scope'); await scope('future')
  await wait(() => window.__DITING_TEST__.S.open.translationModel === 'm2')
  ok('Future-only model change preserves history and makes no calls', JSON.stringify((await snap()).segments) === before && inline.length === start)
  await win.locator('.dt-bar select').selectOption('ja'); await scope('future')
  ok('Future-only language change preserves prior translation targets', (await snap()).segments.every(s => s.trTarget === 'en') && inline.length === start)
  await T(() => { const t = window.__DITING_TEST__; t.S.open.segments[0].trState = 'fail'; t.emit() })
  await win.locator('[data-act="retryAll"]').click()
  await wait(() => window.__DITING_TEST__.S.open.segments[0].trState === 'done')
  rec = await snap()
  ok('Batch retry button handles only failure with current model/target', inline.length === start + 1 && rec.segments[0].trModel.id === 'm2' && rec.segments[0].trTarget === 'ja' && rec.segments.slice(1).every(s => s.trModel.id === 'm1' && s.trTarget === 'en'))
  await T(() => { const t = window.__DITING_TEST__; t.S.open.segments[1].trState = 'fail'; t.emit() })
  start = inline.length; await choose('translation', 'Model A'); await scope('failed')
  await wait(() => window.__DITING_TEST__.S.open.segments[1].trState === 'done')
  ok('Failed scope leaves successes untouched', inline.length === start + 1 && (await snap()).segments[0].trModel.id === 'm2')
  start = inline.length; await choose('translation', 'Model B'); await scope('all')
  await wait(() => window.__DITING_TEST__.S.open.segments.every(s => s.trState === 'done' && s.trModel.id === 'm2' && s.trTarget === 'ja'))
  ok('Retranslate-all processes every existing sentence', inline.length - start === (await snap()).segments.length)
  await T(() => { localStorage.setItem('plugin.diting.fix', 'true'); window.__DITING_TEST__.emit() })
  await choose('translation', 'Translation only'); await scope('future')
  await win.waitForSelector('.dt-model-correction-hint', { state: 'visible' })
  ok('Dedicated translation model exposes correction limitation', (await win.locator('.dt-model-correction-hint').innerText()).includes('专用翻译'))
  start = inline.length; await win.locator('.dt-bar select').selectOption('en'); await scope('all')
  await wait(() => window.__DITING_TEST__.S.open.segments.every(s => s.trState === 'done' && s.trModel.id === 'mt'))
  ok('Correction does not silently switch a translation-only model', inline.slice(start).every(b => b.model_id === 'mt' && b.action === 'translate'))
  await shot('13-space-light')
  await win.getByRole('button', { name: '切换明暗模式', exact: true }).click(); await win.waitForTimeout(700); await shot('14-space-dark'); ok('Actual theme control enters dark mode', await T(() => document.documentElement.dataset.mode === 'dark'))
  await mainWin('setContentSize', 880, 800); await shot('15-space-narrow')
  ok('Narrow model controls remain within Space', await T(() => [...document.querySelectorAll('.dt-model-row,.dt-model-field')].every(e => e.scrollWidth <= e.clientWidth + 2)))
  await mainWin('setContentSize', 1440, 900)
  await win.locator('.dt-config-link').filter({ hasText: '术语表' }).click()
  await win.locator('.dt-config-term button').click()
  await wait(() => !window.__DITING_TEST__.prefs().terms['拉比频率'])
  ok('Glossary term deletion works through Space', await win.locator('.dt-config-term').count() === 0)
  await win.keyboard.press('Escape')
  await win.locator('.dt-config-link').filter({ hasText: '设为 Space 默认' }).click()
  ok('Space defaults save plugin preference', await T(() => window.__DITING_TEST__.prefs().asrModel === 'probe/speech' && window.__DITING_TEST__.prefs().translationModel === 'mt'))
  const cfg = JSON.parse(fs.readFileSync(path.join(home, 'config.json'), 'utf8'))
  ok('Global model slots retain original values', cfg.asr.backend === 'local' && cfg.models.translate === 'm1')
  const segments = JSON.stringify((await snap()).segments)
  await win.locator('.dt-bar select').selectOption('')
  ok('Translation Off retains finished content', JSON.stringify((await snap()).segments) === segments)
  await win.locator('[data-act="stop"]').click(); await until('ended', s => s.phase === 'idle')
  rec = await snap(); await win.waitForTimeout(800)
  const saved = JSON.parse(fs.readFileSync(path.join(vault, rec.folder, '.record.json'), 'utf8'))
  ok('Record model choices and per-sentence receipts reach disk', saved.asrModel === 'probe/speech' && saved.translationModel === 'mt' && saved.segments.every(s => ['probe/speech','local'].includes(s.asrModel.id) && s.trModel.id === 'mt' && s.trTarget === 'en'))
  await T(() => localStorage.setItem('tangu_locale', 'en'))
  await win.reload(); await win.waitForTimeout(3500); await enter('Diting')
  await win.getByText('Space model acceptance', { exact: true }).first().click()
  await win.waitForSelector('.dt-h1'); await win.waitForTimeout(800)
  ok('Reload restores record selection and provenance', await T(() => window.__DITING_TEST__.S.open.asrModel === 'probe/speech' && window.__DITING_TEST__.S.open.translationModel === 'mt' && window.__DITING_TEST__.S.open.segments.every(s => s.trTarget === 'en')))
  await win.waitForFunction(() => document.querySelector('.dt-model-controls')?.textContent.includes('Speech probe'), null, { timeout: 15000 }); ok('Cold Space boot loads model menu without visiting Chat', (await win.locator('.dt-model-controls').innerText()).includes('Translation only')); await shot('16-space-english')
  fs.writeFileSync(path.join(process.env.SHOTS || path.join(__dirname, '../.shots'), 'model-evidence.json'), JSON.stringify({ saved, calls: inline.map(b => ({ action: b.action, model: b.model_id, language: b.language })), cloudCalls: cloudAsr.length, global: { asr: cfg.asr, models: cfg.models } }, null, 2))
}
